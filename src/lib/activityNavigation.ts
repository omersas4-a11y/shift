import type { ActivityEvent, Candidate } from '../types';

export interface CandidateNavigationTarget {
  candidateId: string;
  messageId?: string;
  requestId: number;
}

/** Older message events have no IDs, so match their actor and local display minute. */
export function resolveCandidateMessageTarget(
  event: ActivityEvent,
  candidates: Candidate[],
): Pick<CandidateNavigationTarget, 'candidateId' | 'messageId'> | null {
  if (event.category !== 'candidates') return null;
  if (event.candidateId) return { candidateId: event.candidateId, messageId: event.messageId || undefined };
  if (event.text !== 'נוספה הודעה לשיחת מועמד') return null;

  const eventTime = Date.parse(event.createdAt);
  if (!Number.isFinite(eventTime)) return null;
  const displayMinute = new Intl.DateTimeFormat('he-IL', { dateStyle: 'short', timeStyle: 'short' }).format(eventTime);
  const matches = candidates.flatMap(candidate => (candidate.messages ?? [])
    .filter(message => message.senderName === event.actor && message.timestamp === displayMinute)
    .map(message => ({ candidateId: candidate.id, messageId: message.id, delay: eventTime - Number(message.id.split('-')[0]) })));
  if (matches.length === 1) return { candidateId: matches[0].candidateId, messageId: matches[0].messageId };

  // Message IDs generated by the app begin with Date.now(). Choose the unique
  // message saved immediately before the event, rather than guessing by name.
  const recent = matches.filter(match => Number.isFinite(match.delay) && match.delay >= 0 && match.delay < 120_000)
    .sort((left, right) => left.delay - right.delay);
  if (!recent.length || (recent.length > 1 && recent[1].delay - recent[0].delay < 1_000)) return null;
  return { candidateId: recent[0].candidateId, messageId: recent[0].messageId };
}
